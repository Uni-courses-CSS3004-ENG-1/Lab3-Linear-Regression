section("Step 6 — Polynomial regression")

# One row per degree, indexed by the degree itself.
poly_rows = {}
for degree in DEGREES:
    scores = cv_scores(poly_model(degree), X, y)
    poly_rows[degree] = {"train_r2": scores["train_r2"].mean(),
                         "test_r2": scores["test_r2"].mean()}
poly = pd.DataFrame.from_dict(poly_rows, orient="index")
poly["change"] = poly["test_r2"].diff()

rows = []
for degree, row in poly.iterrows():
    change = "—" if degree == DEGREES[0] else f"{row.change:+.4f}"
    rows.append([degree, f"{row.train_r2:.4f}", f"{row.test_r2:.4f}", change])
    print(f"degree {degree}: train R² = {row.train_r2:.4f}, "
          f"test R² = {row.test_r2:.4f}, test change = {change}")
md_table(["Degree", "Train R² (5-fold mean)", "Test R² (5-fold mean)", "Test R² change"],
         rows)

first_degree, max_degree = DEGREES[0], DEGREES[-1]
best_degree = poly.test_r2.idxmax()
# The lowest degree whose test R² is within MIN_GAIN of the best one.
stop_degree = poly.index[poly.test_r2 >= poly.test_r2.max() - MIN_GAIN][0]
train_monotonic = bool((poly.train_r2.diff().dropna() >= -1e-12).all())
print(f"Highest mean test R² at degree {best_degree}")
print(f"Test R² stops improving (within {MIN_GAIN} of the best) at degree {stop_degree}")
print("Train R² never decreases with degree:", train_monotonic)
report.append(f"Highest mean test R²: degree **{best_degree}**")
report.append("")

fig, ax = plt.subplots(figsize=(7, 5))
ax.plot(poly.index, poly.train_r2, marker="o", label="Train R² (5-fold mean)")
ax.plot(poly.index, poly.test_r2, marker="s", label="Test R² (5-fold mean)")
ax.set_xticks(poly.index)
ax.set_xlabel("Polynomial degree")
ax.set_ylabel("R²")
ax.set_title(f"Polynomial regression on {best}: R² vs degree")
ax.grid(alpha=0.3)
ax.legend()
fig.tight_layout()
fig.savefig(FIG_DIR / "step6_r2_vs_degree.png", dpi=150)
plt.close(fig)

later = poly.test_r2[poly.index > stop_degree]  # degrees past the stopping point
where = ["**Where test R² stops improving.**"]
if later.empty:
    where.append(f"Degree {max_degree} beats every lower degree by more than {MIN_GAIN}, so "
                 f"there is no clear stopping point within degrees 1–{max_degree} on this split.")
else:
    start_r2 = poly.test_r2[first_degree]
    if stop_degree == first_degree:
        rise = f"Test R² is {start_r2:.4f} at degree 1 and does not improve meaningfully after that"
    else:
        rise = (f"Test R² rises from {start_r2:.4f} at degree 1 to "
                f"{poly.test_r2[stop_degree]:.4f} at degree {stop_degree} and stops improving there")
    where.append(rise + f": no higher degree beats it by more than {MIN_GAIN} ("
                 + ", ".join(f"degree {d}: {r2:.4f}" for d, r2 in later.items()) + ").")
paragraph(*where)

why = [
    "**Why train R² keeps climbing while test R² does not.**",
    f"Train R² goes from {poly.train_r2[first_degree]:.4f} at degree 1 to "
    f"{poly.train_r2[max_degree]:.4f} at degree {max_degree}"
    + (" and never decreases." if train_monotonic else "."),
    "A higher-degree polynomial contains every lower-degree one (set the extra coefficients to "
    "zero), so on the cars it is fitted to it can only match or beat the lower degree.",
    "Each extra term is extra freedom to bend the curve toward the particular training cars, "
    "including their random scatter.",
]
if not later.empty:
    why.append(f"That scatter does not repeat in the held-out fold, so past degree {stop_degree} "
               "the extra bends buy nothing on test data, or lose a little.")
if stop_degree == 2:
    # Describe the curve from the signs of the fitted degree-2 coefficients.
    slope, curvature = poly_model(2).fit(X, y)[-1].coef_
    direction = "falls" if slope < 0 else "rises"
    bend = "flattens out" if slope * curvature < 0 else "gets steeper"
    why.append(f"Degree 2 already captures the real shape (fuel efficiency {direction} as "
               f"`{best}` grows, and the curve {bend} at high `{best}`), so the higher degrees "
               "only fit noise.")
low, high = X[best].min(), X[best].max()
why.append(f"This relies on standardizing `{best}` inside the pipeline first: its raw values span "
           f"{low:g}–{high:g}, so the degree-{max_degree} term would reach about "
           f"{high ** max_degree:.1e}, which makes plain least squares numerically unstable.")
paragraph(*why)

