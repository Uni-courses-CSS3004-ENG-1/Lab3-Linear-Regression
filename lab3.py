step5 = pd.DataFrame(step5_rows)
step5["change"] = step5["mean_r2"].diff()  # NaN for the first row

rows = []
for i, row in step5.iterrows():
    label = row.added if i == 0 else "+ " + row.added
    change_text = "—" if i == 0 else f"{row.change:+.4f}"
    rows.append([label, f"{row.mean_r2:.4f}", f"{row.std_r2:.4f}", change_text])
    print(f"{label:<22} mean test R² = {row.mean_r2:.4f} "
          f"(std {row.std_r2:.4f})  change = {change_text}")
