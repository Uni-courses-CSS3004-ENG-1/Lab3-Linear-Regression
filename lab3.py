# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def section(title: str) -> None:
    print(f"\n{'=' * 70}\n{title}\n{'=' * 70}")
    report.extend(["", f"## {title}", ""])


def md_table(header: list[str], rows: list[list[object]]) -> None:
    report.append("| " + " | ".join(header) + " |")
    report.append("|" + "---|" * len(header))
    for row in rows:
        report.append("| " + " | ".join(str(cell) for cell in row) + " |")
    report.append("")


def paragraph(*sentences: str) -> None:
    report.extend([" ".join(sentences), ""])


def code_list(names: list[str]) -> str:
    """Format names as `a`, `b` and `c` for the written answers."""
    quoted = [f"`{name}`" for name in names]
    if len(quoted) == 1:
        return quoted[0]
    return ", ".join(quoted[:-1]) + " and " + quoted[-1]


def regression_metrics(y_true: pd.Series, y_pred: np.ndarray) -> dict[str, float]:
    mse = mean_squared_error(y_true, y_pred)
    return {
        "MAE": mean_absolute_error(y_true, y_pred),
        "MSE": mse,
        "RMSE": np.sqrt(mse),
        "R²": r2_score(y_true, y_pred),
    }


def cv_scores(model: BaseEstimator, X: pd.DataFrame, y: pd.Series) -> dict[str, np.ndarray]:
    """Per-fold train R², test R² and test RMSE on the shared 5-fold split."""
    scores = cross_validate(model, X, y, cv=CV, return_train_score=True,
                            scoring={"r2": "r2", "rmse": "neg_root_mean_squared_error"})
    return {
        "train_r2": scores["train_r2"],
        "test_r2": scores["test_r2"],
        "test_rmse": -scores["test_rmse"],
    }


def poly_model(degree: int) -> Pipeline:
    """Scale first, so high powers of the raw feature don't break least squares."""
    return make_pipeline(
        StandardScaler(),
        PolynomialFeatures(degree=degree, include_bias=False),
        LinearRegression(),
    )


