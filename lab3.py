if best_row < len(step5) - 1:
    answer.append(f"The model with every numeric feature scores {all_r2:.4f}, "
                  f"below the best row ({step5.mean_r2[best_row]:.4f}).")
answer.append(
    "So throwing every column into the model is not a free improvement: what a feature adds "
    "depends on what the model already contains, not on its own correlation with the target. "
    "A feature that repeats known information only gives least squares another coefficient to "
    "estimate from the same cars, so each addition has to earn its place on held-out data."
)
